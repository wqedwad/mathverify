def sx(expr, claim, truth_ok, vars_=None, name="", dod=None):
    return run(f"simplify[{name or expr}]={claim}", ir("simplify_expression", {"expr": expr}, vars_=vars_ or [{"name": "x"}], dod=dod, shape="expression"),
               sol("expression", claim), truth_ok)

def do(expr, claim, truth_ok, kind="interval", name="", vars_=None, dod=None):
    return run(f"domain_of[{name or expr}]={claim}", ir("domain_of", {"expr": expr, "var": "x"}, vars_=vars_ or [{"name": "x"}], dod=dod, shape="interval"),
               sol(kind, claim), truth_ok)

